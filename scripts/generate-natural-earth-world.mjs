import { createHash } from 'node:crypto';
import { writeFile } from 'node:fs/promises';

const SOURCE_COMMIT = 'f1890d9f152c896d250a77557a5751a93d494776';
const SOURCE_SHA256 = '6866c877d39cba9c357620878839b336d569f8c662d3cfab4cb1dbe2d39c977f';
const SOURCE_URL = `https://raw.githubusercontent.com/nvkelso/natural-earth-vector/${SOURCE_COMMIT}/geojson/ne_110m_admin_0_countries.geojson`;
const OUTPUT = new URL('../src/geography/natural-earth-world-110m.generated.ts', import.meta.url);
const QUANTIZATION = 10;
const CHUNK_SIZE = 120;

function stringProperty(properties, name) {
  const value = properties[name];
  return typeof value === 'string' && value.trim() !== '' && value !== '-99' ? value.trim() : '';
}

function quantize(value) {
  return Math.round(value * QUANTIZATION) / QUANTIZATION;
}

function normalizeRing(ring) {
  const output = [];
  for (const coordinate of ring) {
    if (!Array.isArray(coordinate) || coordinate.length < 2) continue;
    const longitude = quantize(Number(coordinate[0]));
    const latitude = quantize(Number(coordinate[1]));
    if (!Number.isFinite(longitude) || !Number.isFinite(latitude)) continue;
    const previous = output.at(-1);
    if (previous?.[0] === longitude && previous[1] === latitude) continue;
    output.push([longitude, latitude]);
  }
  const first = output[0];
  const last = output.at(-1);
  if (first !== undefined && last !== undefined && first[0] === last[0] && first[1] === last[1]) {
    output.pop();
  }
  return output.length >= 3 ? output : [];
}

function normalizePolygons(geometry) {
  const polygons = geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates;
  return polygons
    .map((polygon) => polygon.map(normalizeRing).filter((ring) => ring.length >= 3))
    .filter((polygon) => polygon.length > 0);
}

function featureTuple(feature) {
  const { properties, geometry } = feature;
  if (geometry?.type !== 'Polygon' && geometry?.type !== 'MultiPolygon') return null;
  const id = stringProperty(properties, 'ADM0_A3');
  const iso2 = stringProperty(properties, 'ISO_A2');
  const iso3 = stringProperty(properties, 'ISO_A3');
  const numeric = stringProperty(properties, 'ISO_N3');
  const name = stringProperty(properties, 'NAME_EN') || stringProperty(properties, 'NAME');
  const aliases = [
    id,
    iso2,
    iso3,
    numeric,
    stringProperty(properties, 'SOV_A3'),
    stringProperty(properties, 'POSTAL'),
    stringProperty(properties, 'WB_A2'),
    stringProperty(properties, 'WB_A3'),
    stringProperty(properties, 'NAME'),
    name,
    stringProperty(properties, 'NAME_LONG'),
    stringProperty(properties, 'ADMIN'),
    stringProperty(properties, 'SOVEREIGNT'),
    stringProperty(properties, 'BRK_A3'),
    stringProperty(properties, 'BRK_NAME'),
  ].filter((value, index, values) => value !== '' && values.indexOf(value) === index);
  const polygons = normalizePolygons(geometry);
  if (id === '' || name === '' || polygons.length === 0) return null;
  return [
    id,
    iso2,
    iso3,
    numeric,
    name,
    quantize(Number(properties.LABEL_X ?? 0)),
    quantize(Number(properties.LABEL_Y ?? 0)),
    aliases,
    polygons,
  ];
}

const response = await fetch(SOURCE_URL);
if (!response.ok) throw new Error(`Natural Earth download failed: HTTP ${response.status}`);
const source = await response.text();
const sourceHash = createHash('sha256').update(source).digest('hex');
if (sourceHash !== SOURCE_SHA256) {
  throw new Error(`Natural Earth source hash changed: ${sourceHash} != ${SOURCE_SHA256}`);
}

const collection = JSON.parse(source);
if (collection?.type !== 'FeatureCollection' || !Array.isArray(collection.features)) {
  throw new Error('Natural Earth source is not a GeoJSON FeatureCollection.');
}
const countries = collection.features.map(featureTuple).filter(Boolean);
if (countries.length !== 177) {
  throw new Error(`Natural Earth country count changed: ${countries.length} != 177`);
}

const serialized = JSON.stringify(countries);
const chunks = [];
for (let index = 0; index < serialized.length; index += CHUNK_SIZE) {
  chunks.push(JSON.stringify(serialized.slice(index, index + CHUNK_SIZE)));
}

const output = `/* This file is generated by scripts/generate-natural-earth-world.mjs. */
/* Natural Earth vector tag v5.1.2, Admin-0 Countries 1:110m, public domain. */

export const NATURAL_EARTH_WORLD_110M_SOURCE_COMMIT = '${SOURCE_COMMIT}';
export const NATURAL_EARTH_WORLD_110M_SOURCE_SHA256 = '${SOURCE_SHA256}';
export const NATURAL_EARTH_WORLD_110M_FEATURE_COUNT = ${countries.length};

export type NaturalEarthPosition = readonly [longitude: number, latitude: number];
export type NaturalEarthRing = readonly NaturalEarthPosition[];
export type NaturalEarthPolygon = readonly NaturalEarthRing[];
export type NaturalEarthCountry = readonly [
  id: string,
  iso2: string,
  iso3: string,
  numeric: string,
  name: string,
  labelLongitude: number,
  labelLatitude: number,
  aliases: readonly string[],
  polygons: readonly NaturalEarthPolygon[],
];

const serializedCountries = [
${chunks.map((chunk) => `  ${chunk},`).join('\n')}
].join('');

let countryCache: readonly NaturalEarthCountry[] | undefined;

export function naturalEarthCountries110m(): readonly NaturalEarthCountry[] {
  countryCache ??= JSON.parse(serializedCountries) as readonly NaturalEarthCountry[];
  return countryCache;
}
`;

await writeFile(OUTPUT, output, 'utf8');
console.log(
  `Generated ${countries.length} Natural Earth countries (${serialized.length} compact bytes) at ${OUTPUT.pathname}`,
);
